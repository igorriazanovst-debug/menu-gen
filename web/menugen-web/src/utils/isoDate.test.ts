// ISO_DATE_V1: календарные даты не должны зависеть от часового пояса.
//
// Поводом стал разбор на dev: в окне «Заполнить из меню» приёмы были подписаны
// «20 августа», а записи легли на 21-е. Считалось так:
//
//   new Date('2026-08-20T00:00:00').toISOString().split('T')[0]  // '2026-08-19'
//
// Локальная полночь, переведённая в UTC, — это предыдущие сутки для всех поясов
// восточнее Гринвича. Подписи уезжали на день назад, а бэкенд складывал
// «дата начала + смещение» правильно — расхождение и вылезло у пользователя.
import { addDaysIso, dateToIso, todayIso } from './isoDate';

describe('addDaysIso', () => {
  test('следующий день — это следующий день', () => {
    expect(addDaysIso('2026-08-20', 1)).toBe('2026-08-21');
  });

  test('нулевой сдвиг оставляет дату на месте', () => {
    // Именно здесь старый код терял сутки: '2026-08-20' → '2026-08-19'.
    expect(addDaysIso('2026-08-20', 0)).toBe('2026-08-20');
  });

  test('неделя вперёд', () => {
    expect(addDaysIso('2026-08-20', 6)).toBe('2026-08-26');
  });

  test('переход через конец месяца', () => {
    expect(addDaysIso('2026-08-31', 1)).toBe('2026-09-01');
  });

  test('переход через конец года', () => {
    expect(addDaysIso('2026-12-31', 1)).toBe('2027-01-01');
  });

  test('високосный февраль', () => {
    expect(addDaysIso('2028-02-28', 1)).toBe('2028-02-29');
  });

  test('сдвиг назад', () => {
    expect(addDaysIso('2026-09-01', -1)).toBe('2026-08-31');
  });

  test('непонятная строка возвращается как есть', () => {
    // Подставить «сегодня» вместо мусора значит молча увести не на тот день.
    expect(addDaysIso('вчера', 1)).toBe('вчера');
    expect(addDaysIso('', 1)).toBe('');
  });
});

describe('dateToIso', () => {
  test('берёт локальные компоненты даты, а не UTC', () => {
    // 23:30 по местному времени — это всё ещё сегодня, каким бы ни был UTC.
    const late = new Date(2026, 7, 20, 23, 30, 0);
    expect(dateToIso(late)).toBe('2026-08-20');
  });

  test('ранние часы не превращаются во вчера', () => {
    const early = new Date(2026, 7, 20, 0, 30, 0);
    expect(dateToIso(early)).toBe('2026-08-20');
  });

  test('однозначные месяц и день дополняются нулём', () => {
    expect(dateToIso(new Date(2026, 0, 5))).toBe('2026-01-05');
  });
});

describe('todayIso', () => {
  test('совпадает с локальной датой', () => {
    expect(todayIso()).toBe(dateToIso(new Date()));
  });
});
