// MG_VERIFYDEEPLINK: возврат в приложение после подтверждения e-mail.
//
// Ссылка из письма ведёт на веб-страницу — иначе её не открыть на компьютере.
// На телефоне это раздражало: человек регистрировался в приложении, а
// оказывался в мобильном вебе. Теперь страница после успеха предлагает
// «Открыть в приложении» и уводит по схеме menugen://verified?email=…
//
// Токен через схему НЕ передаём: любое приложение может зарегистрировать ту же
// схему и перехватить ссылку. Токен гасит веб-страница, сюда приходит только
// адрес — чтобы подставить его в форму входа. Когда появятся App Links
// (проверка владения доменом), перехват станет невозможен и токен можно будет
// отдавать приложению — разбор ссылки останется этим же.

/// Схема приложения. Зарегистрирована в AndroidManifest.
const kAppScheme = 'menugen';

/// Хост ссылки «e-mail подтверждён».
const kVerifiedHost = 'verified';

/// Адрес из ссылки подтверждения, или null — если ссылка не про это.
///
/// Пустой `email` — законный случай: подтверждение состоялось, просто адрес не
/// передали. Тогда возвращаем пустую строку, а не null: открыть приложение и
/// показать отметку всё равно нужно.
String? verifiedEmailFromLink(Uri? uri) {
  if (uri == null) return null;
  if (uri.scheme != kAppScheme) return null;
  // menugen://verified?email=… — хост, но на всякий случай принимаем и путь:
  // разные браузеры нормализуют такие ссылки по-разному.
  final target = uri.host.isNotEmpty ? uri.host : uri.path.replaceAll('/', '');
  if (target != kVerifiedHost) return null;
  return (uri.queryParameters['email'] ?? '').trim();
}
