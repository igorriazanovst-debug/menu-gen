// MG_SHAREERR: почему не удалось выдать доступ к списку.
//
// Доступ выдаётся только тем, кто уже зарегистрирован в MenuGen: бэкенд ищет
// пользователя по адресу или номеру и отвечает «Пользователь не найден», если
// такого нет. Раньше клиент подменял любой отказ общим «проверьте email» —
// человек видел одно и то же и когда ошибся в адресе, и когда адрес верен, а
// аккаунта с ним нет, и когда прав на список не хватает.
import '../../core/api/api_exception.dart';

/// Текст ошибки для формы выдачи доступа.
String grantErrorText(Object error, {required bool byPhone}) {
  final what = byPhone ? 'номером' : 'адресом';

  if (error is! ApiException) return 'Не удалось выдать доступ. Попробуйте ещё раз.';
  if (error.isNetwork) return 'Нет связи с сервером. Проверьте интернет.';

  final message = error.message.trim();
  // «Пользователь не найден» — самая частая причина, и она требует пояснения:
  // приглашать незарегистрированных нельзя.
  if (message.toLowerCase().contains('не найден')) {
    return 'Пользователя с таким $what нет в MenuGen. Доступ можно выдать только '
        'тому, кто уже зарегистрирован в приложении.';
  }
  if (error.statusCode == 403) return 'Нет прав управлять доступом к этому списку.';
  if (error.isThrottled) return 'Слишком много попыток. Подождите минуту.';
  if (message.isNotEmpty && message != 'Ошибка сервера') return message;
  return 'Не удалось выдать доступ (${error.statusCode}).';
}
