"""MG_PACKSIZE: разбор строки фасовки.

Случаи перенесены из веба (`utils/packageSize.test.ts`) намеренно, один в один:
там тот же разбор подставляет пачку в дневник. Две реализации одного правила
разошлись бы незаметно — обе молча возвращают None, когда не разобрали.

Плюс случаи, которых в вебе не было: они пришли из того, что реально лежит в
`Product.default_unit` после импорта справочников сетей.
"""

from decimal import Decimal

import pytest

from apps.fridge.package_size import package_grams


@pytest.mark.parametrize(
    "raw,expected",
    [
        ("250г", 250),
        ("930мл", 930),
        ("300 г", 300),
        ("1кг", 1000),
        ("1,5л", 1500),
        ("0.5 л", 500),
    ],
)
def test_мера_читается(raw, expected):
    assert package_grams(raw) == Decimal(expected)


@pytest.mark.parametrize(
    "raw,expected",
    [
        ("4.5г x 4 шт", 18),
        # Кириллическую «х» на этикетках от латинской не отличить.
        ("2г х 25шт", 50),
        ("100 г × 3", 300),
    ],
)
def test_пачка_из_нескольких_считается_целиком(raw, expected):
    assert package_grams(raw) == Decimal(expected)


@pytest.mark.parametrize("raw", ["упак", "шт", "", None, "   ", "банка", "по вкусу"])
def test_нечитаемое_не_повод_выдумывать(raw):
    assert package_grams(raw) is None


@pytest.mark.parametrize("raw", ["50кг", "0 г"])
def test_нелепые_величины_отбрасываются(raw):
    """Двадцати килограммов в одной упаковке холодильника не бывает.

    Такое число значит, что разобрали не ту часть строки, — а молча записанный
    неверный вес потом тихо спишет из холодильника не то количество.

    Отрицательных здесь нет намеренно. «-5 г» правило прочитает как 5: минус в
    выражение не входит — так же, как и в вебе. Строки фасовки с минусом не
    существует, и расходиться из-за несуществующего ввода значит завести между
    двумя реализациями ровно то незаметное различие, которого мы избегаем.
    """
    assert package_grams(raw) is None


def test_размер_вытаскивается_из_хвоста_названия():
    assert package_grams("Молоко Простоквашино 3.2%, 930мл") == Decimal(930)


def test_процент_жирности_не_путается_с_мерой():
    """«3.2%» стоит раньше и мерой не является — брать надо 930 мл."""
    assert package_grams("Кефир 3.2%, 930 мл") == Decimal(930)


@pytest.mark.parametrize("raw", ["говядина", "лоток", "грудка", "лосось"])
def test_буква_внутри_слова_мерой_не_считается(raw):
    """«г» в «говядине» и «л» в «лотке» — не единицы.

    Без этой проверки правило ловило бы первую попавшуюся букву и выдавало вес
    там, где числа нет вовсе.
    """
    assert package_grams(raw) is None
