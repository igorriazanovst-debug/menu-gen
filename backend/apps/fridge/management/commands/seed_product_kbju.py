def _norm(name: str) -> str:
    """нормализация имени для матчинга: lower, ё->е, схлопнуть пробелы."""
    s = (name or "").strip().lower().replace("ё", "е")
    return re.sub(r"\s+", " ", s)


# нормализованный индекс справочника
_KBJU_INDEX = {_norm(k): v for k, v in KBJU.items()}


class Command(BaseCommand):
    help = "Проставить КБЖУ (на 100 г) сид-продуктам по выверенному справочнику."

    def add_arguments(self, parser):
        parser.add_argument(
            "--dry-run",
            action="store_true",
            help="Только показать, что изменится, без записи в БД.",
        )
        parser.add_argument(
            "--force",
            action="store_true",
            help="Перезаписывать КБЖУ даже у продуктов с уже непустым nutrition.",
        )

    def handle(self, *args, **opts):
        dry = opts["dry_run"]
        force = opts["force"]

        updated = skipped_has_nutrition = unmatched = 0
        to_update = []

        for p in Product.objects.all():
            row = _KBJU_INDEX.get(_norm(p.name))
            if row is None:
                unmatched += 1
                continue
            has_nutrition = isinstance(p.nutrition, dict) and len(p.nutrition) > 0
            if has_nutrition and not force:
                skipped_has_nutrition += 1
                continue
            kcal, prot, fat, carb = row
            p.calories_per_100g = kcal
            p.nutrition = {"calories": kcal, "proteins": prot, "fats": fat, "carbs": carb}
            to_update.append(p)
            updated += 1

        if dry:
            self.stdout.write(self.style.WARNING("DRY-RUN — изменения НЕ сохранены."))
            for p in to_update[:20]:
                self.stdout.write(f"  {p.name}: {p.nutrition}")
            if len(to_update) > 20:
                self.stdout.write(f"  … и ещё {len(to_update) - 20}")
        else:
            for p in to_update:
                p.save(update_fields=["calories_per_100g", "nutrition"])

        self.stdout.write(
            self.style.SUCCESS(
                f"Готово. Обновлено: {updated}; "
                f"пропущено (уже есть nutrition): {skipped_has_nutrition}; "
                f"нет в справочнике: {unmatched}; "
                f"всего в справочнике: {len(KBJU)}."
            )
        )
