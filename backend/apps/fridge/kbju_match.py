"""MG_KBJUMATCH: подобрать каталожный продукт под свободно набранное название.

Зачем. Человек заводит свой продукт «фарш телятина» — и получает запись без
КБЖУ, хотя в каталоге рядом лежит «Фарш из телятины» с 220 ккал. Поиск его не
показал, и это не случайность: `search_regex` склеивает слова запроса через
``\\s+``, то есть требует их подряд и ровно в том порядке. «фарш телятина» и
«фарш ИЗ телятины» для него разные строки.

Здесь порядок слов и предлоги не важны. Сравниваются множества основ:
«фарш телятина» → {фарш, телятин}, «Фарш из телятины» → {фарш, телятин}.

Чего здесь намеренно НЕТ:

* **Своего нормализатора.** Регистр, «ё», скобки, кавычки, количество в начале
  — всё это уже умеет `normalize_alias`, а окончания — `ru_stem`. Третье
  определение «похожих названий» в проекте разошлось бы с первыми двумя молча.
* **Слияния записей.** Здесь только ПОДСКАЗКА, которую человек принимает или
  отклоняет. Поэтому правила мягче, чем у `dedup_products.wordorder_key`: тот
  сливает записи насовсем и предлоги не выбрасывает намеренно — цена ошибки
  там несопоставима. Мягкое правило в жёстком месте и наоборот — две разные
  беды, и разводить их надо явно.
* **Кандидатов без КБЖУ.** Подсказка нужна ради чисел; запись без чисел
  предложить нечего.
"""

from __future__ import annotations

import re

from django.db.models import Q

from apps.common.morphology import stem_prefix

from .aliases import normalize_alias

# Служебные слова: они ничего не говорят о том, что это за продукт, но ломают
# сравнение по множеству слов. «Фарш из телятины» и «фарш телятина» — одно и
# то же, «масло для жарки» и «масло жарка» — тоже.
STOPWORDS = frozenset(
    """
    и или а но из с со в во на над под за к ко у о об обо от до по при для
    без про через между the of and
    """.split()
)

# Короче этого слово не несёт смысла по отдельности («с», «из»), а длинные
# числа и артикулы в подсказке только мешают.
_MIN_TOKEN = 2
_WORD_RE = re.compile(r"[^\W\d_]+", re.UNICODE)


def content_tokens(name: str) -> frozenset:
    """Основы значащих слов названия.

    Пустое множество означает «сравнивать не с чем» — например, название из
    одних предлогов или из одних цифр. Такое название подсказок не получает:
    совпадёт с чем угодно, а значит ни с чем.
    """
    base = normalize_alias(name)
    out = set()
    for raw in _WORD_RE.findall(base):
        if len(raw) < _MIN_TOKEN or raw in STOPWORDS:
            continue
        out.add(stem_prefix(raw))
    return frozenset(out)


def match_score(a: frozenset, b: frozenset) -> float:
    """Насколько два набора основ про одно и то же: от 0 до 1.

    Доля общих слов среди всех встретившихся. «фарш телятина» против «фарш из
    телятины» даёт 1.0 — предлог выброшен раньше. «фарш телятина» против
    «фарш куриный» даёт 0.33: одно слово из трёх, и это справедливо мало.
    """
    if not a or not b:
        return 0.0
    return len(a & b) / len(a | b)


# Ниже этого совпадение случайно.
#
# Порог поднят с 0.5 после прогона на боевых данных. По запросу «фарш
# телятина» в выдачу попадали «Фарш» (254 ккал) и «Телятина» (113 ккал) —
# ровно по 0.5, одно слово из двух. Но телятина это не фарш из телятины, а
# мясо: 113 против 220, вдвое мимо. Пока точное совпадение в каталоге есть,
# такие строки прячутся за ним и вреда не делают; стоит ему не найтись — и
# форма предложит вдвое меньшее число, а человек нажмёт «подставить».
#
# 0.6 означает «одного общего слова из двух мало». «Нежирный фарш из
# телятины» (0.67) проходит — это хотя бы фарш и хотя бы из телятины.
MIN_SCORE = 0.6


def has_kbju(product) -> bool:
    """Есть ли чем делиться. Те же два поля, что проверяет mg_kbju_gaps."""
    return product.calories_per_100g is not None or bool(product.nutrition)


def suggest_from_catalog(name: str, limit: int = 5) -> list:
    """Каталожные продукты с КБЖУ, похожие на введённое название.

    Возвращает список пар (продукт, совпадение), самые похожие первыми.
    """
    from .models import Product
    from .visibility import catalog_q

    tokens = content_tokens(name)
    if not tokens:
        return []

    # Сузить выборку до запроса в базу, а не тянуть каталог в память: в нём
    # за тридцать тысяч записей. Основа — всегда начало слова в любой его
    # форме, поэтому подстрока находит все формы сразу.
    prefilter = Q()
    for t in sorted(tokens, key=len, reverse=True)[:3]:
        prefilter |= Q(name__icontains=t)

    # «Без КБЖУ» выражено так же, как в mg_kbju_gaps: пустой nutrition — это
    # `{}` либо NULL. Два разных определения в одном проекте дали бы два
    # разных ответа и спор о том, какое правдивее.
    no_kbju = Q(calories_per_100g__isnull=True) & (Q(nutrition__isnull=True) | Q(nutrition={}))

    scored = []
    qs = (
        Product.objects.filter(catalog_q())
        .filter(prefilter)
        .exclude(no_kbju)
        .only("id", "name", "calories_per_100g", "nutrition", "category_fk")[:300]
    )
    for p in qs:
        if not has_kbju(p):
            continue
        score = match_score(tokens, content_tokens(p.name))
        if score >= MIN_SCORE:
            scored.append((p, score))

    # Сначала по совпадению, при равном — короткое имя вперёд: «Фарш из
    # телятины» полезнее, чем «Фарш из телятины охлаждённый Мираторг, 400г».
    scored.sort(key=lambda pair: (-pair[1], len(pair[0].name), pair[0].id))
    return scored[:limit]
