ALLERGEN_KEYS = tuple(a["key"] for a in ALLERGENS)
_BY_KEY = {a["key"]: a for a in ALLERGENS}
_LABEL_TO_KEY = {a["label"].lower(): a["key"] for a in ALLERGENS}

_WORD_RE = re.compile(r"[а-я]+")


def _norm(s):
    return (s or "").strip().lower().replace("ё", "е")


def public_allergens():
    """Список для UI: key, label, full, group (без внутренних стеммов)."""
    return [{"key": a["key"], "label": a["label"], "full": a["full"], "group": a["group"]} for a in ALLERGENS]


def label_for(key):
    a = _BY_KEY.get(key)
    return a["label"] if a else key


def resolve_allergy(value):
    """Строка из профиля → ключ аллергена из 14, или None (кастомный аллерген).

    Понимает: сам ключ ('milk'), точную метку ('Молоко'), а также имя,
    классифицирующееся ровно в один аллерген (напр. 'сыр' → milk).
    """
    if not isinstance(value, str):
        return None
    v = value.strip()
    if not v:
        return None
    if v in _BY_KEY:
        return v
    low = v.lower()
    if low in _LABEL_TO_KEY:
        return _LABEL_TO_KEY[low]
    keys = classify_ingredient_names([v])
    return keys[0] if len(keys) == 1 else None


def _name_hits(name):
    """Множество ключей аллергенов, найденных в одном имени."""
    low = _norm(name)
    if not low:
        return set()
    tokens = _WORD_RE.findall(low)
    found = set()
    for a in ALLERGENS:
        excl = a["exclude"]
        hit = False
        for t in tokens:
            if t in excl:
                continue
            for stem in a["stems"]:
                if t.startswith(stem):
                    hit = True
                    break
            if hit:
                break
        if not hit and a["substr"]:
            for sub in a["substr"]:
                if sub in low:
                    hit = True
                    break
        if hit:
            found.add(a["key"])
    return found


def classify_ingredient_names(names):
    """Список имён (ингредиенты и/или название блюда) → отсортированный список ключей."""
    found = set()
    for n in names or []:
        found |= _name_hits(n)
    return sorted(found)


def classify_recipe(recipe):
    """Аллергены рецепта по его ингредиентам + названию. Возвращает список ключей."""
    names = []
    title = getattr(recipe, "title", None)
    if title:
        names.append(title)
    for ing in getattr(recipe, "ingredients", None) or []:
        if isinstance(ing, dict):
            nm = ing.get("name")
            if nm:
                names.append(nm)
        elif isinstance(ing, str):
            names.append(ing)
    return classify_ingredient_names(names)
