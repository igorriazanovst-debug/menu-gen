VOWELS = "аеиоуыэюя"

# Окончания по группам алгоритма Snowball. Внутри группы важен порядок: ищем
# самое длинное подходящее, иначе «ившись» отсеклось бы как «сь».
PERFECTIVE_GERUND_1 = ("вшись", "вши", "в")  # только после «а» или «я»
PERFECTIVE_GERUND_2 = ("ившись", "ывшись", "ивши", "ывши", "ив", "ыв")
REFLEXIVE = ("ся", "сь")
