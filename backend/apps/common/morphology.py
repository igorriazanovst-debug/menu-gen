SUPERLATIVE = ("ейше", "ейш")
DERIVATIONAL = ("ость", "ост")

# Ниже этой длины слово не трогаем: у коротких слов «окончание» — половина
# слова, и основа получилась бы бессмысленно широкой («уха» → «ух»).
MIN_WORD = 4
MIN_STEM = 3


def _rv(word: str) -> int:
    """Начало области RV: всё после первой гласной. Окончания ищем только там,
    иначе у «еда» отсеклось бы «а» вместе со смыслом слова."""
    for i, ch in enumerate(word):
        if ch in VOWELS:
            return i + 1
    return len(word)


def _cut(word: str, rv: int, endings, after_vowel: str = "") -> str | None:
    """Отрезает первое подходящее окончание в RV. after_vowel — буква, которая
    обязана стоять перед окончанием (для групп «после а/я»)."""
    for ending in endings:
        if not word.endswith(ending):
            continue
        start = len(word) - len(ending)
        if start < rv:
            continue
        if after_vowel:
            if start == 0 or word[start - 1] not in after_vowel:
                continue
            start -= 1  # сама «а»/«я» — часть окончания
        return word[:start]
    return None


def ru_stem(word: str) -> str:
    """Основа русского слова. Всегда является началом исходного слова."""
    word = (word or "").lower().replace("ё", "е")
    if len(word) < MIN_WORD or not re.search(r"[а-я]", word):
        return word

    rv = _rv(word)

    # 1. Деепричастие, иначе возвратность + (прилагательное | глагол | сущ.)
    stem = _cut(word, rv, PERFECTIVE_GERUND_1, after_vowel="ая") or _cut(word, rv, PERFECTIVE_GERUND_2)
    if stem is None:
        word = _cut(word, rv, REFLEXIVE) or word
        stem = _cut(word, rv, ADJECTIVE)
        if stem is not None:
            # Причастие приклеивается перед окончанием прилагательного:
            # «тушенный» = «туш» + «енн» + «ый».
            stem = _cut(stem, rv, PARTICIPLE_1, after_vowel="ая") or _cut(stem, rv, PARTICIPLE_2) or stem
        else:
            stem = _cut(word, rv, VERB_1, after_vowel="ая") or _cut(word, rv, VERB_2) or _cut(word, rv, NOUN) or word

    # 2. Хвостовая «и»
    if stem.endswith("и") and len(stem) - 1 >= rv:
        stem = stem[:-1]

    # 3. Отглагольное «ость»
    stem = _cut(stem, rv, DERIVATIONAL) or stem

    # 4. Двойная «н», превосходная степень, мягкий знак
    if stem.endswith("нн"):
        stem = stem[:-1]
    else:
        cut = _cut(stem, rv, SUPERLATIVE)
        if cut is not None:
            stem = cut[:-1] if cut.endswith("нн") else cut
    if stem.endswith("ь"):
        stem = stem[:-1]

    # Слишком короткая основа ищет что попало — тогда лучше искать как набрано.
    return stem if len(stem) >= MIN_STEM else word


def stem_prefix(term: str) -> str:
    """Часть слова, по которой ищем: основа либо само слово, если оно короткое."""
    word = (term or "").strip()
    if len(word) < MIN_WORD:
        return word
    stem = ru_stem(word)
    # Основа не длиннее слова — берём её, но не пустую.
    return stem or word
