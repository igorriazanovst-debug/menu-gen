"""MG_MORPHSEARCH: поиск по словоформам — «тушеная» находит «тушенное».

Поиск сравнивал подстроки, поэтому находил только то, что записано ровно так же,
как набрано. «Тушеная» не находила «тушенная» (лишняя «н»), «яйца» не находили
«яйцо», «супы» не находили «суп»: у слова другое окончание — и совпадения нет.

Решение — отбрасывать окончание у слова из запроса и искать по основе. «Тушеная»
и «тушенная» дают одну основу «тушен», и она есть в обеих формах; «яйца» и
«яйцо» — «яйц». Формы в базе трогать не нужно: основа всегда является началом
слова, а ищем мы вхождение подстроки.

Алгоритм — Snowball для русского (он же «Портер для русского»), общепринятый
стеммер: отсечение окончаний по группам (деепричастие, возвратность,
прилагательное/причастие, глагол, существительное), затем чистка «и», «нн»,
превосходной степени и мягкого знака. Реализован здесь, а не подключён
библиотекой, потому что нужен ровно он: одна функция без зависимостей,
одинаково работающая и на Postgres (прод), и на SQLite (локальные тесты).

Чего он не умеет — менять корень: «курица» → «куриц», а «куриный» → «курин»,
одно другого не найдёт. Это ограничение любого стеммера без словаря; для
словарной леммы понадобился бы pymorphy и его база форм.
"""

from __future__ import annotations

