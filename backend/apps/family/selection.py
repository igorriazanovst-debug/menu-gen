"""MG_ONEFAMILY: единственный ответ на вопрос «в какой семье пользователь».

Раньше этот вопрос решался восемью независимыми копиями — в `family`, `fridge`
(дважды), `menu`, `payments`, `subscriptions`, `shopping` и в экране удаления
аккаунта, плюс девятая точка в `diary` искала тем же способом членство. Шесть
копий смотрели сначала на членство, две (`shopping`, удаление аккаунта) — сначала
на владение семьёй. Пока копий восемь, никакое «переключение семьи» (T-26)
невозможно: переключишь в одном месте — остальные семь останутся на прежней
семье, и человек получит холодильник одной семьи со списком покупок другой.

Отдельно про сортировку. Все копии брали `.first()` у запроса без сортировки, и
это выглядело как «повезёт — не повезёт». На деле правило жёсткое: Django
неотсортированному запросу сам добавляет `order_by("pk")`, то есть побеждало
членство с наименьшим номером — самое старое. Своя семья заводится в момент
регистрации (`apps/users/views.py` `_bootstrap_user`), значит её членство всегда
старше любого приглашения, полученного позже, и выигрывало всегда. Отсюда
следствие, которое и привело к этой задаче: приглашение существующего
пользователя в семью не работало ни у кого и никогда — приглашённый продолжал
видеть свою семью, без общего холодильника, меню, списка покупок и премиума
пригласившей семьи. Замер на проде (chat-84): людей с двумя членствами — один,
и у него премиум семьи не работал.

Здесь сортировка выписана явно — не чтобы изменить поведение, а чтобы оно
перестало зависеть от умолчаний ORM и стало видно в коде.

Правило (сегодняшнее поведение, сохранено дословно):

1. самое старое членство пользователя — его семья;
2. если членств нет вовсе — семья, которой он владеет (тоже самая старая).

Пункт 2 — запасной путь: при регистрации и при заведении семьи из админки
членство создаётся вместе с семьёй, так что до него доходит только случай, когда
членство удалили руками.

Две копии (`shopping`, удаление аккаунта) спрашивали про владение ПЕРВЫМ. Разница
видна лишь у того, кто владеет одной семьёй, а состоит в другой и в своей
членства не имеет, — на проде таких нет. Приведено к варианту большинства и к
варианту самого модуля `family`.

MG_ACTIVEFAMILY (T-26) добавил к правилу первый пункт — выбор самого человека.
Читается он здесь, в одном месте, поэтому переключение семьи меняет разом всё:
холодильник, меню, покупки, платежи, премиум, дневник и экран удаления аккаунта.
Ради этого правило и сводили.
"""

from __future__ import annotations

from .models import Family, FamilyMember


def _is_real_user(user) -> bool:
    return bool(user) and bool(getattr(user, "is_authenticated", False))


def memberships(user):
    """Все членства человека, от старого к новому. Пустой список — если их нет."""
    if not _is_real_user(user):
        return []
    return list(FamilyMember.objects.select_related("family").filter(user=user).order_by("id"))


def current_membership(user):
    """Членство, от имени которого пользователь сейчас работает, или None.

    Порядок правил:

    1. MG_ACTIVEFAMILY — семья, которую человек выбрал сам. Учитывается только
       пока он в ней состоит: указатель на семью, из которой его исключили,
       равносилен пустому. Проверка идёт при каждом чтении, поэтому исключённый
       человек молча возвращается к своей семье, а не упирается в закрытую дверь
       с ошибкой на каждом экране.
    2. Иначе — самое старое членство: выбор не сделан, ведём себя как раньше.

    Возвращает членство, а не семью, потому что кое-где важен именно участник:
    дневник, вода и вес помечают им место записи (см. T-28).
    """
    rows = memberships(user)
    if not rows:
        return None
    active_id = getattr(user, "active_family_id", None)
    if active_id:
        for row in rows:
            if row.family_id == active_id:
                return row
    return rows[0]


def current_family(user):
    """Семья, в которой пользователь сейчас работает, или None."""
    if not _is_real_user(user):
        return None
    membership = current_membership(user)
    if membership is not None:
        return membership.family
    return Family.objects.filter(owner=user).order_by("id").first()
