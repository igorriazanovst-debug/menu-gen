"""MG_NOTENOISE: примечание из рецепта — не продукт.

В каталог и в списки покупок приезжали «Соль по вкусу», «Масло для обжарки»,
«По вкусу: базилик», «Яица - 1 шт. С1», «– 1 ст. 200 мл орзо». На проде таких
записей в каталоге набралось 27 с фразой-примечанием и ещё 45 с цифрами, а
связей рецептов с такими названиями — 94. В списке покупок на 49 рецептов это
дало 154 позиции вместо сотни, и часть из них — не еда, а куски строк.

Отсекать это должен был ИИ: в промпте канонизации прямо сказано «если это не
продукт — canon=null». Но он отсекает не всё, а второго рубежа не было: дальше
по коду название проверялось только на длину и на «не число» (_is_seedable).
Одной проверки, которая иногда ошибается, мало там, где ошибка молча оседает в
общем каталоге и потом всплывает у каждого, кто соберёт список из этого меню.

Поэтому правило здесь детерминированное и работает без ИИ:

- фраза-примечание («по вкусу», «для подачи», «для жарки») вырезается, а
  остаток остаётся продуктом: «Зелень по вкусу» → «Зелень», «По вкусу: базилик»
  → «Базилик». Так позиция не пропадает, а сливается с той же записью, которая
  в списке уже есть;
- количество и мера («2 зубчика», «4-5 веточек», «1 ст. ложка», «по 90г»)
  вырезаются тоже: количество живёт в отдельных полях связи, в названии ему
  места нет;
- если после вырезания не осталось ничего или остался обрывок в один символ —
  название было примечанием целиком, и продукта в нём нет.

Чего правило НЕ делает: не трогает падежи («чеснока» так и останется) и не
трогает проценты жирности — «Сливки 10%», «Творог 5%», «Молоко 2.5%» это
нормальные записи каталога, а не мусор. Голое число в конце без процента
(«Сливочное масло 72», «Молоко 0») — другое дело: это обрыв строки.
"""

import re

# Фразы-примечания. Набраны по тому, что реально лежит в каталоге на проде,
# а не по догадкам: каждая строка ниже встречается там хотя бы раз.
_NOTE_RE = re.compile(
    r"(?:\s*[:,–—-]\s*)?\b(?:"
    r"по\s+вкусу"
    r"|по\s+желанию"
    r"|при\s+желании"
    r"|опционально"
    r"|для\s+подачи"
    r"|для\s+сервировки"
    r"|для\s+украшени\w*"
    r"|для\s+посыпки"
    r"|для\s+смазывани\w*"
    r"|для\s+смазки"
    r"|для\s+жарки"
    r"|для\s+обжарки"
    r"|для\s+фритюра"
    r"|для\s+панировки"
    r"|на\s+раскатку"
    r"|на\s+посыпку"
    r"|на\s+смазку"
    r")\b\s*:?",
    re.IGNORECASE,
)

# Количество с мерой. Проценты жирности сюда намеренно не входят.
_MEASURE = (
    r"(?:г|гр|кг|мл|л|шт|ст\.?\s*ложк\w*|ст\.?\s*л|ч\.?\s*ложк\w*|ч\.?\s*л"
    r"|зубчик\w*|зуб|веточк\w*|веточек|щепотк\w*|щепоть|пучок|пучка"
    r"|стакан\w*|банк\w*|пачк\w*|уп\.?|кусочк\w*|ломтик\w*|долек|дольк\w*)"
)
_NUM = r"\d+(?:[.,]\d+)?(?:\s*[-–—]\s*\d+(?:[.,]\d+)?)?"

# «2 зубчика», «4-5 веточек», «1 ст. ложка», «200 мл», «~200 г», «по 90г».
_QTY_RE = re.compile(r"\b(?:по\s*)?~?\s*%s\s*%s\b\.?" % (_NUM, _MEASURE), re.IGNORECASE)
# Число в начале названия — всегда количество: «3 яйца вареных», «2 зубчика
# чеснока». Меры при нём может и не быть, поэтому правило отдельное.
_LEAD_NUM_RE = re.compile(r"^\s*%s\s+" % _NUM)
# Мера без числа в начале строки: «– 1 ст. 200 мл орзо» после вырезания чисел.
_LEAD_JUNK_RE = re.compile(r"^[\s.,:;+*~–—-]+")
_TAIL_JUNK_RE = re.compile(r"[\s.,:;+*~–—-]+$")
# Голое число в конце без процента: «Сливочное масло 72», «Молоко 0», «Молоко3».
_BARE_TAIL_NUM_RE = re.compile(r"\s*\d+\s*$")
# Обрывок сорта/категории яиц в хвосте: «Яица - 1 шт. С1».
_EGG_GRADE_RE = re.compile(r"\bс\s*[0-2]\b\s*$", re.IGNORECASE)

# Слово-мера, оставшееся в одиночестве, продуктом не является.
_MEASURE_ONLY = re.compile(r"^\s*%s\s*$" % _MEASURE, re.IGNORECASE)


def clean_ingredient_name(name):
    """Название ингредиента без примечаний и количества.

    Возвращает пустую строку, если от названия ничего не осталось: значит оно
    было примечанием целиком («по вкусу», «для подачи») и продукта в нём нет.
    Вызывающий код такую позицию пропускает.
    """
    s = (name or "").strip()
    if not s:
        return ""

    # Процент жирности прячем на время чистки, чтобы «Сливки 10%» не потеряли
    # хвост на правиле про голое число, и возвращаем на место в конце.
    pcts = []

    def _hide(m):
        pcts.append(m.group(0))
        return "\x00%d\x00" % (len(pcts) - 1)

    s = re.sub(r"\d+(?:[.,]\d+)?\s*%", _hide, s)

    s = _NOTE_RE.sub(" ", s)
    s = _QTY_RE.sub(" ", s)
    s = _LEAD_NUM_RE.sub("", s)
    s = _EGG_GRADE_RE.sub(" ", s)
    s = re.sub(r"\s+", " ", s)
    s = _LEAD_JUNK_RE.sub("", s)
    s = _TAIL_JUNK_RE.sub("", s)
    if "\x00" not in s:
        s = _BARE_TAIL_NUM_RE.sub("", s)
    s = _TAIL_JUNK_RE.sub("", s).strip()

    for i, p in enumerate(pcts):
        s = s.replace("\x00%d\x00" % i, p)
    s = re.sub(r"\s+", " ", s).strip()

    if len(s) < 2 or _MEASURE_ONLY.match(s):
        return ""
    return s[:1].upper() + s[1:]


def is_ingredient_noise(name):
    """True, если от названия после чистки не остаётся продукта."""
    return not clean_ingredient_name(name)


def is_ingredient_fragment(name):
    """True, если в названии есть примечание или количество.

    Шире, чем is_ingredient_noise: «Масло для обжарки» и «Апельсин ~200 г» —
    продукты, но записывать их в каталог под такими именами нельзя. Правило
    отделяет записи, которые надо чистить, от тех, что просто не являются едой.
    """
    s = (name or "").strip()
    if not s:
        return False
    return clean_ingredient_name(s) != s
