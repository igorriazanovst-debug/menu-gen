def test_чистка_названий_с_прода(raw, expected):
    assert clean_ingredient_name(raw) == expected


@pytest.mark.parametrize(
    "raw",
    [
        "Сливки 10%",
        "Сливки 10 %",
        "Творог 5%",
        "Творог 9%",
        "Молоко 2.5%",
        "Молоко 3.2%",
        "Сметана 15%",
        "сметана 10%",
        "Масло 82%",
        "Сгущенка 1%",
        "Уксус столовый 9%",
        "Сливки жирностью 18 %",
        "молоко сгущенное 2,5%",
    ],
)
def test_жирность_не_трогаем(raw):
    """Процент — часть названия товара, по нему их и различают в магазине."""
    assert clean_ingredient_name(raw) == raw[:1].upper() + raw[1:]


@pytest.mark.parametrize(
    "raw",
    [
        "Лук репчатый",
        "Яйцо куриное",
        "Помидоры черри",
        "Сыр адыгейский",
        "Морковь по-корейски",
        "Рис",
        "Соль",
        "Основа для супа фо",
        "Сыр твёрдый любой",
        "Крабовые палочки",
    ],
)
def test_нормальные_названия_не_меняются(raw):
    """Правило не должно трогать то, что и так продукт."""
    assert clean_ingredient_name(raw) == raw


@pytest.mark.parametrize(
    "raw",
    [
        "по вкусу",
        "По вкусу",
        "по желанию",
        "опционально",
        "для подачи",
        "Для подачи",
        "для украшения",
        "",
        "   ",
        "–",
        "- 1 шт",
        "200 мл",
        "2 ст. ложки",
        "щепотка",
    ],
)
def test_примечание_целиком_продуктом_не_является(raw):
    assert clean_ingredient_name(raw) == ""
    assert is_ingredient_noise(raw) is True


def test_морковь_по_корейски_не_путается_с_по_вкусу():
    """«по-корейски» через дефис — часть названия, а не начало примечания.

    Правило смотрит на «по вкусу» и «по желанию» целиком, поэтому предлог сам
    по себе ничего не запускает. Проверка стоит здесь потому, что соблазн
    вырезать «по ...» одним махом велик, а цена — потерянный продукт.
    """
    assert clean_ingredient_name("Морковь по-корейски") == "Морковь по-корейски"


@pytest.mark.parametrize(
    "raw,expected",
    [
        # MG_NOTENOISE2: число в начале названия — всегда количество, меры при
        # нём может и не быть. На проде так осели «3 яйца вареных» и
        # «4 яйца я использовала 18 перепелиных яиц».
        ("3 яйца вареных", "Яйца вареных"),
        ("2 зубчика чеснока", "Чеснока"),
        ("1 лимон", "Лимон"),
    ],
)
def test_число_в_начале_это_количество(raw, expected):
    assert clean_ingredient_name(raw) == expected


def test_число_в_середине_названия_не_трогаем():
    """Правило смотрит только на начало: «Молоко 2.5%» трогать нельзя."""
    assert clean_ingredient_name("Молоко 2.5%") == "Молоко 2.5%"
