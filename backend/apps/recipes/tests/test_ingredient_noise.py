class TestХвостПримечания:
    """MG_NOTETAIL: у примечания бывает дополнение, и вырезать надо всё.

    «Масло для смазывания формы» превращалось в «Масло формы»: фраза уходила, а
    дополнение оставалось. Нашлось это на проде при чистке мусора — запись
    собирались удалить, и в список покупок вместо неё полезло бы вот это.
    """

    @pytest.mark.parametrize(
        "raw,expected",
        [
            ("Масло для смазывания формы", "Масло"),
            ("Масло для смазки формы", "Масло"),
            ("Яйцо для смазки", "Яйцо"),
            ("Сыр для начинки пирога", "Сыр"),
            ("Масло растительное для жарки 2-3 ст. ложки", "Масло растительное"),
            ("Зелень укропа 4-5 веточек для подачи", "Зелень укропа"),
        ],
    )
    def test_дополнение_уходит_вместе_с_примечанием(self, raw, expected):
        assert clean_ingredient_name(raw) == expected

    @pytest.mark.parametrize(
        "raw,expected",
        [
            ("Для подачи: кунжут", "Кунжут"),
            ("Для подачи по желанию : сметана", "Сметана"),
            ("По вкусу: базилик", "Базилик"),
        ],
    )
    def test_после_двоеточия_стоит_продукт_и_он_остаётся(self, raw, expected):
        """Двоеточие меняет порядок: продукт после примечания, хвост трогать нельзя."""
        assert clean_ingredient_name(raw) == expected

    @pytest.mark.parametrize("raw", ["Тесто для пельменей", "Тесто для вареников", "Соус для пасты"])
    def test_для_чего_это_не_действие(self, raw):
        """«Для пельменей» — часть названия товара, а не примечание рецепта."""
        assert clean_ingredient_name(raw) == raw
